import com.gauscan.app.presentation.navigation.AppNavigation
import com.gauscan.app.presentation.theme.GauScanTheme
import dagger.hilt.android.AndroidEntryPoint

@AndroidEntryPoint
class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        installSplashScreen()
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()
        setContent {
            GauScanTheme {
                AppNavigation()
            }
        }
    }
}